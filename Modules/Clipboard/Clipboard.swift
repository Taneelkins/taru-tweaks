import AppKit
import SwiftUI

// Clipboard history. Text, images and copied files, pinned items on top, ⌘⇧C opens the picker and
// Return pastes straight into the app you were in. Password managers mark secrets as concealed and
// those never get saved. Idea from Vorssaint's Clipboard history.
struct ClipItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, image, files }
    var id = UUID()
    var kind: Kind
    var text: String?
    var image: String?
    var paths: [String]?
    var app: String?
    var date = Date()
    var pinned = false

    var preview: String {
        switch kind {
        case .text: return (text ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
        case .image: return "Image"
        case .files: return (paths ?? []).map { ($0 as NSString).lastPathComponent }.joined(separator: ", ")
        }
    }
}

final class Clipboard: ObservableObject {
    static let shared = Clipboard()
    static let hotKeyID: UInt32 = 601
    // apps whose copies are secrets even when they forget the concealed mark
    static let ignoredApps: Set<String> = ["com.1password.1password", "com.agilebits.onepassword7", "com.bitwarden.desktop", "com.apple.keychainaccess", "com.apple.Passwords"]
    private static let skip: Set<String> = ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "org.nspasteboard.ConcealedType"]

    @Published var enabled = UserDefaults.standard.object(forKey: "clip.enabled") as? Bool ?? true { didSet { UserDefaults.standard.set(enabled, forKey: "clip.enabled"); sync(); registerKey() } }
    @Published var keep = UserDefaults.standard.object(forKey: "clip.keep") as? Int ?? 300 { didSet { UserDefaults.standard.set(keep, forKey: "clip.keep"); trim(); save() } }
    @Published var mask = (UserDefaults.standard.object(forKey: "clip.mask") as? NSNumber)?.uint64Value ?? 0x120000 { didSet { UserDefaults.standard.set(mask, forKey: "clip.mask"); registerKey() } }
    @Published var key = (UserDefaults.standard.object(forKey: "clip.key") as? NSNumber)?.int64Value ?? 8 { didSet { UserDefaults.standard.set(key, forKey: "clip.key"); registerKey() } }
    @Published private(set) var items: [ClipItem] = []

    let dir: URL = {
        let d = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0].appendingPathComponent("TaruTweaks/Clipboard")
        try? FileManager.default.createDirectory(at: d.appendingPathComponent("images"), withIntermediateDirectories: true)
        return d
    }()
    private var file: URL { dir.appendingPathComponent("history.json") }
    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    private var saveWork: DispatchWorkItem?
    private lazy var picker = ClipPicker()

    func start() {
        if let d = try? Data(contentsOf: file), let list = try? JSONDecoder().decode([ClipItem].self, from: d) { items = list }
        registerKey()
        sync()
    }

    private func sync() {
        timer?.invalidate(); timer = nil
        guard enabled else { return }
        lastChange = NSPasteboard.general.changeCount
        // the pasteboard has no change notification, everyone polls; reading one Int is nearly free
        let t = Timer(timeInterval: 0.8, repeats: true) { [weak self] _ in self?.poll() }
        t.tolerance = 0.3
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func registerKey() {
        HotKeys.shared.set(Self.hotKeyID, mask: mask, key: key, enabled: enabled) { Clipboard.shared.togglePicker() }
    }

    func togglePicker() { picker.toggle() }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skip) else { return }
        let front = NSWorkspace.shared.frontmostApplication
        if let id = front?.bundleIdentifier, Self.ignoredApps.contains(id) { return }
        guard var item = capture(pb) else { return }
        item.app = front?.localizedName
        add(item)
    }

    private func capture(_ pb: NSPasteboard) -> ClipItem? {
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return ClipItem(kind: .files, paths: urls.map(\.path))
        }
        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return ClipItem(kind: .text, text: s.count > 200_000 ? String(s.prefix(200_000)) : s)
        }
        // screenshots and copied images; huge ones aren't worth keeping on disk
        if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff), data.count < 20_000_000,
           let rep = NSBitmapImageRep(data: data), let png = rep.representation(using: .png, properties: [:]) {
            let name = UUID().uuidString + ".png"
            guard (try? png.write(to: dir.appendingPathComponent("images/\(name)"))) != nil else { return nil }
            return ClipItem(kind: .image, image: name)
        }
        return nil
    }

    private func add(_ item: ClipItem) {
        // same text copied again just moves to the top
        if let i = items.firstIndex(where: { $0.kind == item.kind && $0.text == item.text && $0.paths == item.paths && item.kind != .image }) {
            var old = items.remove(at: i)
            old.date = Date(); old.app = item.app ?? old.app
            items.insert(old, at: 0)
        } else {
            items.insert(item, at: 0)
        }
        trim()
        save()
    }

    private func trim() {
        var unpinned = 0
        items = items.filter { i in
            if i.pinned { return true }
            unpinned += 1
            if unpinned <= keep { return true }
            dropImage(i)
            return false
        }
    }

    private func dropImage(_ i: ClipItem) {
        if let n = i.image { try? FileManager.default.removeItem(at: dir.appendingPathComponent("images/\(n)")) }
    }

    private func save() {
        saveWork?.cancel()
        let snapshot = items, url = file
        let w = DispatchWorkItem { if let d = try? JSONEncoder().encode(snapshot) { try? d.write(to: url, options: .atomic) } }
        saveWork = w
        DispatchQueue.global(qos: .utility).asyncAfter(deadline: .now() + 1, execute: w)
    }

    func image(_ i: ClipItem) -> NSImage? { i.image.flatMap { NSImage(contentsOf: dir.appendingPathComponent("images/\($0)")) } }

    func togglePin(_ i: ClipItem) {
        guard let x = items.firstIndex(of: i) else { return }
        items[x].pinned.toggle()
        save()
    }

    func delete(_ i: ClipItem) {
        items.removeAll { $0.id == i.id }
        dropImage(i)
        save()
    }

    func clear() {
        items.filter { !$0.pinned }.forEach(dropImage)
        items.removeAll { !$0.pinned }
        save()
    }

    // put it back on the pasteboard, then ⌘V into whatever app was in front
    func paste(_ i: ClipItem, into app: NSRunningApplication?) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch i.kind {
        case .text: pb.setString(i.text ?? "", forType: .string)
        case .image: if let img = image(i) { pb.writeObjects([img]) }
        case .files: pb.writeObjects((i.paths ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        }
        lastChange = pb.changeCount
        if let x = items.firstIndex(of: i), x > 0 { var m = items.remove(at: x); m.date = Date(); items.insert(m, at: 0); save() }
        app?.activate()
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.08) {
            for down in [true, false] {
                let e = CGEvent(keyboardEventSource: nil, virtualKey: 9, keyDown: down)
                e?.flags = .maskCommand
                e?.post(tap: .cghidEventTap)
            }
        }
    }
}

// MARK: Picker

final class ClipPanel: NSPanel {
    override var canBecomeKey: Bool { true }
}

final class ClipPicker {
    private var panel: ClipPanel?
    private var monitor: Any?
    private var resign: Any?
    private var target: NSRunningApplication?
    let state = ClipPickerState()

    func toggle() { panel?.isVisible == true ? hide() : show() }

    func show() {
        target = NSWorkspace.shared.frontmostApplication
        if target?.processIdentifier == getpid() { target = nil }
        state.query = ""; state.selected = 0
        let p = panel ?? make()
        let screen = NSScreen.screens.first { $0.frame.contains(NSEvent.mouseLocation) } ?? NSScreen.main
        if let f = screen?.visibleFrame { p.setFrameOrigin(NSPoint(x: f.midX - 230, y: f.midY - 200)) }
        p.alphaValue = 0
        p.makeKeyAndOrderFront(nil)
        NSAnimationContext.runAnimationGroup { $0.duration = 0.1; p.animator().alphaValue = 1 }
        state.focus += 1
        monitor = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { [weak self] e in self?.key(e) ?? e }
        resign = NotificationCenter.default.addObserver(forName: NSWindow.didResignKeyNotification, object: p, queue: .main) { [weak self] _ in self?.hide() }
    }

    func hide() {
        if let monitor { NSEvent.removeMonitor(monitor) }; monitor = nil
        if let resign { NotificationCenter.default.removeObserver(resign) }; resign = nil
        panel?.orderOut(nil)
    }

    private func make() -> ClipPanel {
        let p = ClipPanel(contentRect: NSRect(x: 0, y: 0, width: 460, height: 400), styleMask: [.borderless, .nonactivatingPanel], backing: .buffered, defer: true)
        p.isOpaque = false; p.backgroundColor = .clear; p.hasShadow = true
        p.level = .modalPanel; p.hidesOnDeactivate = false
        p.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary, .transient]
        let host = NSHostingView(rootView: ClipPickerView(state: state, onPick: { [weak self] i in self?.pick(i) }))
        host.sizingOptions = []
        host.frame = p.contentRect(forFrameRect: p.frame)
        p.contentView = host
        panel = p
        return p
    }

    private func pick(_ i: ClipItem) {
        let app = target
        hide()
        Clipboard.shared.paste(i, into: app)
    }

    private func key(_ e: NSEvent) -> NSEvent? {
        let list = state.visible
        let cmd = e.modifierFlags.contains(.command)
        switch e.keyCode {
        case 53: hide(); return nil
        case 125: state.selected = min(state.selected + 1, max(0, list.count - 1)); return nil
        case 126: state.selected = max(state.selected - 1, 0); return nil
        case 36, 76: if list.indices.contains(state.selected) { pick(list[state.selected]) }; return nil
        case 51 where cmd: if list.indices.contains(state.selected) { Clipboard.shared.delete(list[state.selected]); state.selected = min(state.selected, max(0, state.visible.count - 1)) }; return nil
        case 35 where cmd: if list.indices.contains(state.selected) { Clipboard.shared.togglePin(list[state.selected]) }; return nil
        default:
            // ⌘1…⌘9 pastes that row
            if cmd, let n = Int(e.charactersIgnoringModifiers ?? ""), (1...9).contains(n), list.indices.contains(n - 1) { pick(list[n - 1]); return nil }
            return e
        }
    }
}

final class ClipPickerState: ObservableObject {
    @Published var query = "" { didSet { selected = 0 } }
    @Published var selected = 0
    @Published var focus = 0

    var visible: [ClipItem] {
        let all = Clipboard.shared.items
        let sorted = all.filter(\.pinned) + all.filter { !$0.pinned }
        guard !query.isEmpty else { return sorted }
        return sorted.filter { $0.preview.localizedCaseInsensitiveContains(query) || ($0.app ?? "").localizedCaseInsensitiveContains(query) }
    }
}

struct ClipPickerView: View {
    @ObservedObject var state: ClipPickerState
    @ObservedObject var clip = Clipboard.shared
    @ObservedObject var theme = Theme.shared
    let onPick: (ClipItem) -> Void
    @FocusState private var searching: Bool

    var body: some View {
        let list = state.visible
        VStack(spacing: 0) {
            HStack(spacing: 8) {
                Image(systemName: "doc.on.clipboard").foregroundStyle(theme.accent)
                TextField("Search clipboard", text: $state.query).textFieldStyle(.plain).font(.system(size: 14)).foregroundStyle(Palette.bone).focused($searching)
                Text("\(clip.items.count)").font(.system(size: 10, weight: .bold, design: .monospaced)).foregroundStyle(Palette.ash)
            }
            .padding(.horizontal, 14).padding(.vertical, 11)
            Rectangle().fill(Palette.rule).frame(height: 1)
            if list.isEmpty {
                Text(clip.items.isEmpty ? "Copy something and it shows up here." : "Nothing matches.").font(.system(size: 12)).foregroundStyle(Palette.ash).frame(maxWidth: .infinity, maxHeight: .infinity)
            } else {
                ScrollViewReader { proxy in
                    ScrollView {
                        LazyVStack(spacing: 0) {
                            ForEach(Array(list.enumerated()), id: \.element.id) { n, item in
                                ClipRow(item: item, number: n < 9 ? n + 1 : nil, selected: n == state.selected)
                                    .id(item.id)
                                    .contentShape(Rectangle())
                                    .onTapGesture { onPick(item) }
                                    .onHover { if $0 { state.selected = n } }
                            }
                        }
                    }
                    .onChange(of: state.selected) { s in if list.indices.contains(s) { proxy.scrollTo(list[s].id) } }
                }
            }
            Rectangle().fill(Palette.rule).frame(height: 1)
            Text("↩ paste   ⌘1–9 quick paste   ⌘P pin   ⌘⌫ delete   esc close").font(.system(size: 9.5, design: .monospaced)).foregroundStyle(Palette.ash)
                .frame(maxWidth: .infinity, alignment: .leading).padding(.horizontal, 14).padding(.vertical, 7)
        }
        .frame(width: 460, height: 400)
        .background(Palette.pit.opacity(0.97))
        .overlay(Rectangle().stroke(Palette.rule, lineWidth: 1))
        .onChange(of: state.focus) { _ in searching = true }
        .onAppear { searching = true }
    }
}

struct ClipRow: View {
    let item: ClipItem
    let number: Int?
    let selected: Bool
    @ObservedObject var theme = Theme.shared

    var body: some View {
        HStack(alignment: .center, spacing: 10) {
            Group {
                switch item.kind {
                case .image:
                    if let img = Clipboard.shared.image(item) { Image(nsImage: img).resizable().aspectRatio(contentMode: .fill) } else { Image(systemName: "photo") }
                case .files: Image(systemName: "doc").foregroundStyle(Palette.ash)
                case .text: Image(systemName: item.pinned ? "pin.fill" : "text.alignleft").foregroundStyle(item.pinned ? theme.accent : Palette.ash)
                }
            }
            .frame(width: item.kind == .image ? 44 : 16, height: item.kind == .image ? 30 : 16).clipped()
            VStack(alignment: .leading, spacing: 2) {
                Text(item.kind == .image ? "Image" : item.preview).font(.system(size: 12.5, design: item.kind == .text ? .monospaced : .default)).foregroundStyle(Palette.bone).lineLimit(2)
                Text([item.app, RelativeDateTimeFormatter().localizedString(for: item.date, relativeTo: Date())].compactMap { $0 }.joined(separator: " · "))
                    .font(.system(size: 9.5, design: .monospaced)).foregroundStyle(Palette.ash)
            }
            Spacer(minLength: 4)
            if item.pinned && item.kind != .text { Image(systemName: "pin.fill").font(.system(size: 9)).foregroundStyle(theme.accent) }
            if let number { Text("⌘\(number)").font(.system(size: 10, weight: .bold, design: .monospaced)).foregroundStyle(selected ? theme.accent : Palette.ash) }
        }
        .padding(.horizontal, 14).padding(.vertical, 7)
        .background(selected ? theme.accent.opacity(0.16) : .clear)
        .overlay(alignment: .leading) { if selected { Rectangle().fill(theme.accent).frame(width: 2) } }
    }
}

struct ClipboardSettings: View {
    @ObservedObject var clip = Clipboard.shared
    var body: some View {
        VStack(alignment: .leading, spacing: 0) {
            PageTitle(title: "Clipboard History", subtitle: "Keeps what you copy (text, images, files) so you can paste it again later. Press the shortcut, type to search, Return pastes into the app you were in.")
            SettingRow(title: "Keep clipboard history") { Switch(on: $clip.enabled) }
            SettingRow(title: "Open history", detail: "\(modifierString(clip.mask))\(keyString(clip.key))") { KeyRecorder(mask: $clip.mask, key: $clip.key) }
            SettingRow(title: "Remember", detail: "Pinned items are always kept") { Seg(options: [("100", 100), ("300", 300), ("1000", 1000)], value: $clip.keep) }
            SettingRow(title: "History", detail: "\(clip.items.count) items, stored only on this Mac") { TweakButton(title: "Clear unpinned") { clip.clear() } }
            Text("Passwords are never saved: anything a password manager marks as secret is skipped, and so is everything copied from 1Password, Bitwarden, Passwords or Keychain Access.")
                .font(.system(size: 10.5, design: .monospaced)).foregroundStyle(Palette.ash).padding(.top, 12)
        }
    }
}
